def main() -> int:
    db.init_db()
    if CATEGORY not in db.list_categories():
        db.add_category(CATEGORY)
        print(f"+ κατηγορία '{CATEGORY}'")

    existing_titles_tpl = {t["title"].strip() for t in db.list_templates()}
    existing_q_kb = {e["question"].strip() for e in db.list_kb_entries()}

    tpl_added, kb_added, skipped = 0, 0, 0
    for s in SCENARIOS:
        title = s["title"].strip()
        content = s["content"].strip()
        if title in existing_titles_tpl:
            skipped += 1
        else:
            db.create_template(title, CATEGORY, content)
            tpl_added += 1
        if title in existing_q_kb:
            pass  # count skip once per scenario below
        else:
            db.create_kb_entry(CATEGORY, title, content)
            kb_added += 1

    print(f"Templates added: {tpl_added}")
    print(f"KB entries added: {kb_added}")
    print(f"Scenarios skipped (dup): {skipped}")
    print()
    print(f"Total templates: {len(db.list_templates())}")
    print(f"Total KB entries: {len(db.list_kb_entries())}")
    print(f"Total categories: {len(db.list_categories())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
