def seed_if_empty() -> tuple[int, int]:
    """Populate KB and tickets only if tables are empty. Returns (kb_added, tickets_added)."""
    init_db()
    kb_added = 0
    ticket_added = 0

    if not list_kb_entries():
        for category, q, a in KB_SEED:
            create_kb_entry(category, q, a)
            kb_added += 1

    if not list_tickets():
        for t in TICKET_SEED:
            create_ticket(**t)
            ticket_added += 1

    seed_templates_if_empty(TEMPLATE_SEED)

    return kb_added, ticket_added


